<script setup lang="ts">
import { computed, onMounted, ref } from 'vue';

import { BButton, BFormCheckbox, BFormInput } from 'bootstrap-vue-next/components';
import { BIconFloppy, BIconKey, BIconBookmark } from 'bootstrap-icons-vue';
import { toastReject, toastSuccess } from '@/plugins/api';
import {
  type AccessTokenPublic,
  Tokens,
  Users,
  type UserTokenPermission,
  type UserUpdate,
  type Wrapper,
} from '@/plugins/api/spec';
import { updateTokenAccess as updateTokenAccessAPI } from '@/plugins/api/helpers';
import { createRandomString } from '@/utils';
import CopyableValue from '@/components/CopyableValue.vue';
import ModalDialog from '@/components/ModalDialog.vue';

/** Length of the passwords generated by the reset icon. */
const PASSWORD_LENGTH = 16;

/**
 * The listing, as editable drafts: every user is loaded into a `UserUpdate`
 * that the inputs write into, and only a click on save sends it to the API.
 */
const users = ref<UserUpdate[]>([]);
const loading = ref(true);
const tokens = ref<AccessTokenPublic[]>([]);
const tokensLoading = ref(false);
const tokenPermissionUser = ref<string | null>(null);
const tokenPermissions = ref<UserTokenPermission[]>([]);

onMounted(() => {
  Users.listUsersUsersGet()
    .then(({ data }) => {
      users.value = (data ?? []) as UserUpdate[];
    })
    .catch(toastReject)
    .finally(() => {
      loading.value = false;
    });
});

function reloadTokens() {
  tokensLoading.value = true;
  Tokens.listTokensTokensListGet()
    .then((response) => {
      tokens.value = response.data;
    })
    .catch(toastReject)
    .finally(() => {
      tokensLoading.value = false;
    });
}

function reloadTokenPermissions(userId: string) {
  Tokens.listPermissionsTokensPermissionGet({ user_id: userId })
    .then((response) => {
      tokenPermissions.value = response.data;
    })
    .catch(toastReject);
}

const tokenPermissionModalOpen = computed({
  // The dialog stays open while a user is selected, even when that user has no
  // (or no matching) token permissions: the token list must remain editable.
  get: () => tokenPermissionUser.value !== null,
  set: (isOpen) => {
    if (!isOpen) {
      tokenPermissions.value = [];
      tokenPermissionUser.value = null;
    }
  },
});

function openTokenPermissions(userId: string) {
  if (tokens.value.length === 0) reloadTokens();
  reloadTokenPermissions(userId);
  tokenPermissionUser.value = userId;
}

type AccessTokenPermission = {
  token: AccessTokenPublic;
  permission?: UserTokenPermission;
};
const permissionLookup = computed(() =>
  Object.fromEntries(tokenPermissions.value.map((permission) => [permission.token_id, permission])),
);
const tokensByWrapper = computed(() => {
  const groups = new Map<Wrapper, AccessTokenPermission[]>();
  tokens.value.forEach((token) => {
    const group = groups.get(token.wrapper);
    const tok = { token, permission: permissionLookup.value[token.token_id as string] };
    if (group) group.push(tok);
    else groups.set(token.wrapper, [tok]);
  });
  return [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([wrapper, group]) => ({
      wrapper,
      tokens: group.sort((a, b) => {
        // Tokens without a comment sort after those that have one.
        if (!a.token.comment) return b.token.comment ? 1 : 0;
        if (!b.token.comment) return -1;
        return a.token.comment.localeCompare(b.token.comment);
      }),
    }));
});

function updateTokenAccess(tokenId: string, access: boolean, owner: boolean = false) {
  if (!tokenPermissionUser.value) return;
  updateTokenAccessAPI(tokenPermissionUser.value, tokenId, access, owner);
}

/**
 * Generates a new password into the draft and shows it. The draft is only sent
 * on save, so the password becomes the user's actual password with that click.
 */
function resetPassword(user: UserUpdate) {
  user.password_plain = createRandomString(PASSWORD_LENGTH);
}

/** Sends the draft - every typed value and the pending password - to the API. */
function save(user: UserUpdate) {
  Users.updateUserUsersPut({ userUpdate: user })
    .then((result) => {
      if (result.data) {
        // Rebase the draft (in place, keeping the input bindings) on what the
        // server stored; the generated password has been applied and is gone.
        Object.assign(user, result.data);
        delete user.password_plain;
      }
      return result;
    })
    .then(toastSuccess)
    .catch(toastReject);
}
</script>
<template>
  <section>
    <h1 class="mb-4">Users</h1>
    <p v-if="loading" class="text-body-secondary">Loading users…</p>
    <p v-else-if="!users.length" class="text-body-secondary">No users yet.</p>

    <div v-for="user in users" :key="user.user_id" class="card mb-3">
      <div class="card-body">
        <div class="d-flex flex-wrap align-items-center gap-2">
          {{ user.full_name }} (<code>{{ user.user_id }}</code
          >)
          <BFormCheckbox v-model="user.is_active" :value="true" :unchecked-value="false" switch
            >Active</BFormCheckbox
          >
          <BFormCheckbox v-model="user.permission_submit_query" switch>
            Query permission
          </BFormCheckbox>
          <BFormCheckbox
            v-model="user.permission_admin"
            switch
            class="me-auto"
            :value="true"
            :unchecked-value="false">
            Admin permission</BFormCheckbox
          >

          <BButton
            size="sm"
            variant="outline-secondary"
            title="Edit user token permissions"
            @click="openTokenPermissions(user.user_id)">
            <BIconBookmark />
          </BButton>

          <BButton
            size="sm"
            variant="outline-secondary"
            title="Generate new password (applied when saving)"
            @click="resetPassword(user)">
            <BIconKey />
          </BButton>

          <BButton size="sm" variant="outline-success" title="Save user" @click="save(user)">
            <BIconFloppy />
          </BButton>
        </div>
        <br />
        <div class="row g-3">
          <div class="col-md-4">
            <label class="form-label small text-body-secondary mb-1" :for="`${user.user_id}-email`">
              Email
            </label>
            <BFormInput
              :id="`${user.user_id}-email`"
              v-model="user.email"
              type="email"
              autocomplete="off" />
          </div>
          <div class="col-md-4">
            <label class="form-label small text-body-secondary mb-1" :for="`${user.user_id}-name`">
              Full name
            </label>
            <BFormInput :id="`${user.user_id}-name`" v-model="user.full_name" />
          </div>
          <div class="col-md-4">
            <label
              class="form-label small text-body-secondary mb-1"
              :for="`${user.user_id}-institution`">
              Institution
            </label>
            <BFormInput :id="`${user.user_id}-institution`" v-model="user.institution" />
          </div>
        </div>
        <p v-if="user.password_plain" class="small mb-0 mt-2">
          New password (applied when saving):
          <copyable-value class="new-password" :value="user.password_plain" />
        </p>
      </div>
    </div>
  </section>

  <ModalDialog
    v-model="tokenPermissionModalOpen"
    title="Manage user access to API tokens"
    size="lg">
    <p v-if="tokensLoading" class="text-body-secondary">Loading tokens…</p>
    <p v-else-if="!tokens.length" class="text-body-secondary">No API tokens defined yet.</p>

    <section v-for="group in tokensByWrapper" :key="group.wrapper" class="mb-4">
      <h6 class="text-body-secondary text-uppercase small mb-2">{{ group.wrapper }}</h6>
      <div class="table-responsive">
        <table class="table table-sm align-middle">
          <thead>
            <tr>
              <th scope="col">Token</th>
              <th scope="col">Description</th>
              <th scope="col">Token active</th>
              <th scope="col">Allowed</th>
              <th scope="col">Owner</th>
            </tr>
          </thead>
          <tbody>
            <tr v-for="token in group.tokens" :key="token.token.token_id">
              <td>
                <code class="token-id">{{ token.token.token_id }}</code>
              </td>
              <td>{{ token.token.comment ?? '—' }}</td>
              <td>
                <span
                  class="badge"
                  :class="token.token.is_active ? 'text-bg-success' : 'text-bg-secondary'">
                  {{ token.token.is_active ? 'Active' : 'Inactive' }}
                </span>
              </td>
              <td>
                <BFormCheckbox
                  :model-value="Boolean(token.permission)"
                  switch
                  @update:model-value="
                    (allowed) => updateTokenAccess(token.token.token_id!, Boolean(allowed))
                  " />
              </td>
              <td>
                <BFormCheckbox
                  :model-value="Boolean(token.permission?.is_owner)"
                  :disabled="Boolean(!token.permission)"
                  switch
                  @update:model-value="
                    (owner) => updateTokenAccess(token.token.token_id!, true, Boolean(owner))
                  " />
              </td>
            </tr>
          </tbody>
        </table>
      </div>
    </section>
  </ModalDialog>
</template>

<style scoped>
/* Generated passwords contain ambiguous characters, so make them selectable
   without the browser wrapping them mid-character. */
.new-password {
  user-select: all;
  word-break: break-all;
}

.token-id {
  /* Token ids are long ids; let them break so the table stays within the dialog. */
  word-break: break-all;
}

.btn svg {
  vertical-align: -0.125em;
}
</style>
